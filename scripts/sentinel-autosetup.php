<?php
/**
 * CLI / Web Runner: Agente Sentinela & AutoSetup (WHMCS + Iugu CC)
 *
 * Executes:
 * 1. Snapshot "No-Hot" into `archived/snapshots/snapshot_<ts>.json`
 * 2. Watchdog de Instalação (PHP 8.1/8.2, extensions, module files, optional Iugu API handshake)
 * 3. Validação de Diagnóstico E2E e Emissão do Sinal Verde
 *
 * Usage:
 *   php scripts/sentinel-autosetup.php
 *   IUGU_ACCOUNT_ID="xxx" IUGU_API_TOKEN="yyy" php scripts/sentinel-autosetup.php
 */

declare(strict_types=1);

require_once __DIR__ . '/../modules/gateways/iugucc/autoload.php';

use WHMCS\Module\Gateway\IuguCC\Config;
use WHMCS\Module\Gateway\IuguCC\IuguHttpClient;
use WHMCS\Module\Gateway\IuguCC\SentinelAuditor;

$rootDir = dirname(__DIR__);

// 1. Etapa 1: Snapshot Consistente ("No-Hot")
$snapshot = SentinelAuditor::createNoHotSnapshot($rootDir, [
    'note' => 'Pre-flight No-Hot Snapshot generated by sentinel-autosetup.php',
]);

// 2. Etapa 2: Watchdog de Instalação & Handshake Opcional
$accountId = (string) (getenv('IUGU_ACCOUNT_ID') ?: '');
$apiToken = (string) (getenv('IUGU_API_TOKEN') ?: '');
$sandboxMode = (string) (getenv('IUGU_SANDBOX') ?: 'true');

$config = null;
$httpClient = null;
if ($accountId !== '' && $apiToken !== '') {
    $config = new Config([
        'accountId' => $accountId,
        'apiToken' => $apiToken,
        'sandboxApiToken' => $apiToken,
        'sandboxMode' => $sandboxMode,
        'sentinelMode' => 'yes',
    ]);
    $httpClient = new IuguHttpClient($config->getActiveApiToken());
}

$watchdog = SentinelAuditor::runInstallationWatchdog($rootDir, $config, $httpClient);

// 3. Etapa 3 & 4: Validação do Parser de Debug Sentinela
$sampleDiagnostic = SentinelAuditor::buildSupportDiagnostic('51', 'preflight_self_test', true, [
    'test_invoice_id' => 9999,
    'masked_card_sample' => '4111111111111111',
]);

$report = [
    'sentinel_version' => '1.1.0',
    'step_1_no_hot_snapshot' => $snapshot,
    'step_2_installation_watchdog' => $watchdog,
    'step_3_4_diagnostic_parser_self_test' => $sampleDiagnostic,
];

echo json_encode($report, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . PHP_EOL;
exit($watchdog['green_light'] ? 0 : 1);
