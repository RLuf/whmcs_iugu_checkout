<?php
/**
 * Iugu Charge Payload Builder
 *
 * Constructs validated JSON payloads for `POST /v1/charge` from WHMCS invoice
 * and client parameters, normalizing Brazilian CPF/CNPJ, phone, and CEP fields.
 *
 * @package    WHMCS\Module\Gateway\IuguCC
 * @target     WHMCS 8.13.7 | PHP 8.1 / 8.2
 */

declare(strict_types=1);

namespace WHMCS\Module\Gateway\IuguCC;

use InvalidArgumentException;

final class PayloadBuilder
{
    /**
     * Builds the request payload for Iugu `POST /v1/charge`.
     *
     * @param Config               $config       Gateway configuration
     * @param string               $iuguToken    One-time token generated by Iugu.js (`response.id`)
     * @param int|string           $invoiceId    WHMCS Invoice ID
     * @param float|string         $amount       Total invoice amount in BRL (e.g., 150.00)
     * @param array<string, mixed> $client       WHMCS clientdetails array
     * @param int                  $installments Number of installments (1..maxInstallments)
     * @param string               $companyName  WHMCS Company Name (default: imovelsite.com.br)
     * @return array<string, mixed>
     */
    public static function buildChargePayload(
        Config $config,
        string $iuguToken,
        int|string $invoiceId,
        float|string $amount,
        array $client,
        int $installments = 1,
        string $companyName = 'imovelsite.com.br'
    ): array {
        $cleanToken = trim($iuguToken);
        if ($cleanToken === '') {
            throw new InvalidArgumentException('Iugu payment token (iugu_token) is required.');
        }

        $floatAmount = round((float) $amount, 2);
        $priceCents = (int) round($floatAmount * 100);
        if ($priceCents <= 0) {
            throw new InvalidArgumentException('Invoice amount must be greater than zero.');
        }

        $validInstallments = max(1, min($config->getMaxInstallments(), $installments));
        if ($validInstallments > 1) {
            $perInstallment = round($floatAmount / $validInstallments, 2);
            if ($perInstallment < $config->getMinInstallmentValue()) {
                $validInstallments = 1;
            }
        }

        $email = trim((string) ($client['email'] ?? ''));
        if ($email === '') {
            $email = 'financeiro@imovelsite.com.br';
        }

        $fullName = trim(
            ((string) ($client['firstname'] ?? '')) . ' ' . ((string) ($client['lastname'] ?? ''))
        );
        if ($fullName === '') {
            $fullName = trim((string) ($client['fullname'] ?? $client['companyname'] ?? 'Cliente WHMCS'));
        }

        $cpfCnpj = self::extractCpfCnpj($client, $config->getCpfCustomFieldName());
        [$phonePrefix, $phoneNumber] = self::extractPhone((string) ($client['phonenumber'] ?? ''));
        $zipCode = self::digitsOnly((string) ($client['postcode'] ?? ''));

        $street = trim((string) ($client['address1'] ?? ''));
        $district = trim((string) ($client['address2'] ?? 'Centro'));
        [$streetName, $streetNumber] = self::splitStreetAndNumber($street);

        $payer = [
            'name' => $fullName,
            'email' => $email,
        ];

        if ($cpfCnpj !== '') {
            $payer['cpf_cnpj'] = $cpfCnpj;
        }
        if ($phonePrefix !== '' && $phoneNumber !== '') {
            $payer['phone_prefix'] = $phonePrefix;
            $payer['phone'] = $phoneNumber;
        }

        if ($zipCode !== '' || $streetName !== '') {
            $payer['address'] = [
                'street' => $streetName !== '' ? $streetName : 'Não informado',
                'number' => $streetNumber !== '' ? $streetNumber : 'S/N',
                'district' => $district !== '' ? $district : 'Centro',
                'city' => trim((string) ($client['city'] ?? 'São Paulo')) ?: 'São Paulo',
                'state' => trim((string) ($client['state'] ?? 'SP')) ?: 'SP',
                'country' => trim((string) ($client['country'] ?? 'BR')) ?: 'BR',
                'zip_code' => $zipCode !== '' ? $zipCode : '01001000',
            ];
        }

        $payload = [
            'token' => $cleanToken,
            'email' => $email,
            'months' => $validInstallments,
            'keep_dunning' => false,
            'order_id' => 'whmcs_' . (string) $invoiceId,
            'items' => [
                [
                    'description' => $config->formatInvoiceDescription($invoiceId, $companyName),
                    'quantity' => 1,
                    'price_cents' => $priceCents,
                ],
            ],
            'payer' => $payer,
            'custom_variables' => [
                [
                    'name' => 'whmcs_invoice_id',
                    'value' => (string) $invoiceId,
                ],
                [
                    'name' => 'whmcs_client_id',
                    'value' => (string) ($client['userid'] ?? $client['id'] ?? ''),
                ],
                [
                    'name' => 'integration_module',
                    'value' => Config::GATEWAY_NAME,
                ],
            ],
        ];

        if ($config->getStatementDescriptor() !== '') {
            $payload['soft_descriptor_light'] = $config->getStatementDescriptor();
        }

        return $payload;
    }

    /**
     * Extracts CPF (11 digits) or CNPJ (14 digits) from WHMCS client details or custom fields.
     *
     * @param array<string, mixed> $client
     */
    public static function extractCpfCnpj(array $client, string $preferredFieldName = 'CPF/CNPJ'): string
    {
        // 1. Direct override or tax_id field
        $candidates = [
            $client['cpf_cnpj'] ?? '',
            $client['tax_id'] ?? '',
            $client['cpf'] ?? '',
            $client['cnpj'] ?? '',
        ];

        foreach ($candidates as $candidate) {
            $digits = self::digitsOnly((string) $candidate);
            if (strlen($digits) === 11 || strlen($digits) === 14) {
                return $digits;
            }
        }

        // 2. Inspect WHMCS customfields array (prioritize preferredFieldName match first, then Mod-11 valid, then length)
        if (!empty($client['customfields']) && is_array($client['customfields'])) {
            $normalizedPref = strtolower(trim($preferredFieldName));
            $fallbackCandidate = '';

            foreach ($client['customfields'] as $customField) {
                if (!is_array($customField)) {
                    continue;
                }
                $fieldName = strtolower(trim((string) ($customField['name'] ?? $customField['fieldname'] ?? $customField['title'] ?? '')));
                $val = self::digitsOnly((string) ($customField['value'] ?? ''));
                if (strlen($val) !== 11 && strlen($val) !== 14) {
                    continue;
                }
                if ($normalizedPref !== '' && ($fieldName === $normalizedPref || str_contains($fieldName, 'cpf') || str_contains($fieldName, 'cnpj'))) {
                    return $val;
                }
                if (self::isValidCpfOrCnpj($val)) {
                    return $val;
                }
                if ($fallbackCandidate === '') {
                    $fallbackCandidate = $val;
                }
            }

            if ($fallbackCandidate !== '') {
                return $fallbackCandidate;
            }
        }

        // 3. Inspect customfields1, customfields2... (prefer Mod-11 valid CPF/CNPJ over 11-digit mobile phone numbers)
        $fallbackIndexed = '';
        for ($i = 1; $i <= 10; $i++) {
            $key = 'customfields' . $i;
            if (isset($client[$key])) {
                $val = self::digitsOnly((string) $client[$key]);
                if (strlen($val) === 11 || strlen($val) === 14) {
                    if (self::isValidCpfOrCnpj($val)) {
                        return $val;
                    }
                    if ($fallbackIndexed === '') {
                        $fallbackIndexed = $val;
                    }
                }
            }
        }

        return $fallbackIndexed;
    }

    /**
     * Validates Brazilian CPF (11 digits) or CNPJ (14 digits) using official Mod-11 checksums.
     */
    public static function isValidCpfOrCnpj(string $raw): bool
    {
        $digits = self::digitsOnly($raw);
        if (strlen($digits) === 11) {
            if (preg_match('/^(\d)\1{10}$/', $digits) === 1) {
                return false;
            }
            for ($t = 9; $t < 11; $t++) {
                $sum = 0;
                for ($c = 0; $c < $t; $c++) {
                    $sum += ((int) $digits[$c]) * (($t + 1) - $c);
                }
                $check = ((10 * $sum) % 11) % 10;
                if (((int) $digits[$t]) !== $check) {
                    return false;
                }
            }
            return true;
        }

        if (strlen($digits) === 14) {
            if (preg_match('/^(\d)\1{13}$/', $digits) === 1) {
                return false;
            }
            $weights1 = [5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2];
            $weights2 = [6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2];
            $sum1 = 0;
            for ($i = 0; $i < 12; $i++) {
                $sum1 += ((int) $digits[$i]) * $weights1[$i];
            }
            $rem1 = $sum1 % 11;
            $d1 = $rem1 < 2 ? 0 : 11 - $rem1;
            if (((int) $digits[12]) !== $d1) {
                return false;
            }
            $sum2 = 0;
            for ($i = 0; $i < 13; $i++) {
                $sum2 += ((int) $digits[$i]) * $weights2[$i];
            }
            $rem2 = $sum2 % 11;
            $d2 = $rem2 < 2 ? 0 : 11 - $rem2;
            return ((int) $digits[13]) === $d2;
        }

        return false;
    }

    /**
     * Splits a Brazilian phone string into [DDD (2 digits), Phone (8-9 digits)].
     *
     * @return array{0: string, 1: string}
     */
    public static function extractPhone(string $rawPhone): array
    {
        $digits = self::digitsOnly($rawPhone);
        // Strip leading country code 55 if present
        if (strlen($digits) >= 12 && str_starts_with($digits, '55')) {
            $digits = substr($digits, 2);
        }
        if (strlen($digits) >= 10) {
            return [substr($digits, 0, 2), substr($digits, 2, 9)];
        }
        return ['', ''];
    }

    /**
     * Splits street address into street name and number when formatted as "Rua Exemplo, 123".
     *
     * @return array{0: string, 1: string}
     */
    private static function splitStreetAndNumber(string $address): array
    {
        if (preg_match('/^(.+?)[,\-\s]+(\d+[A-Za-z0-9\-]*)$/', trim($address), $matches) === 1) {
            return [trim($matches[1]), trim($matches[2])];
        }
        return [trim($address), 'S/N'];
    }

    private static function digitsOnly(string $value): string
    {
        return preg_replace('/\D/', '', $value) ?? '';
    }
}
